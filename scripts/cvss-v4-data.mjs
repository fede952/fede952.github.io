// Generates static/js/tools/cvss/v4-data.mjs from FIRST's official CVSS v4.0
// calculator files vendored unmodified in static/vendor/cvss-v4-calculator@c5b0d40/
// (github.com/FIRSTdotorg/cvss-v4-calculator, BSD-2-Clause). The files define
// globals, so they are evaluated in an empty vm context — data only, no I/O.
// Run after updating the vendored copy:   node scripts/cvss-v4-data.mjs
import fs from 'node:fs';
import vm from 'node:vm';

const DIR = 'static/vendor/cvss-v4-calculator@c5b0d40';
export function loadOfficial() {
  const ctx = vm.createContext({});
  for (const f of ['cvss_lookup.js', 'max_composed.js', 'max_severity.js', 'metrics.js', 'cvss_score.js']) vm.runInContext(fs.readFileSync(`${DIR}/${f}`, 'utf8'), ctx, { filename: f });
  return ctx;
}

if (process.argv[1] && process.argv[1].endsWith('cvss-v4-data.mjs')) {
  const c = loadOfficial();
  const data = { lookup: c.cvssLookup_global, maxComposed: c.maxComposed, maxSeverity: c.maxSeverity, metricOrder: c.expectedMetricOrder };
  const out = `// GENERATED by scripts/cvss-v4-data.mjs — do not edit.
// Data from FIRST's official CVSS v4.0 calculator, commit c5b0d409ae9f57c44264c6ce5f27d89298e1d32a
// (https://github.com/FIRSTdotorg/cvss-v4-calculator): cvss_lookup.js (MacroVector
// scores), max_composed.js, max_severity.js and metrics.js.
// Copyright (c) 2023 FIRST.ORG, Inc., Red Hat, and contributors. SPDX-License-Identifier: BSD-2-Clause
// (full licence text: /vendor/cvss-v4-calculator@c5b0d40/LICENSE)
export default ${JSON.stringify(data)};
`;
  fs.mkdirSync('static/js/tools/cvss', { recursive: true });
  fs.writeFileSync('static/js/tools/cvss/v4-data.mjs', out);
  console.log(`wrote static/js/tools/cvss/v4-data.mjs: ${Object.keys(data.lookup).length} MacroVectors`);
}
